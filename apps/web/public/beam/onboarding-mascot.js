/* beam mascot — the pixel-art beam girl, lifted from the landing hero sprite.
   Exposes window.beamMascot({ className, pose }) → SVG string (viewBox 18×26).
   Render at any size with CSS; image-rendering:pixelated keeps it crisp. */
(function () {
  const PAL = {
    H: '#C9785A', h: '#E89A7B', s: '#FBE2D2', S: '#3D2F4F',
    e: '#2B2530', m: '#C75F75', B: '#F49DAE', c: '#FBF6EE',
    b: '#C9B6E4', o: '#A691CF', l: '#9B7FCB', L: '#7A5BB0', k: '#FBE2D2',
  };

  // 18 wide, front-facing standing pose (same girl as the hero) — two legs
  const GRID = `
....HHHHHHHH......
...HHhhhhhhHH.....
..HhhhhhhhhhhH....
..Hhhsssssshhh....
..Hhssssssssshh...
..Hhseesseessh....
..Hhssssssssshh...
..HhssssBBssshh...
..Hhshssmmsshhh...
..HhhssssssshhH...
...Hhhhsssshhh....
....HccccccH......
...obbbbbbbbo.....
..obbbBbbbBbbbo...
..obbBbbbbbBbbb...
..obbbbbbbbbbb....
..obbbbbbbbbb.....
...lLlLlLlLl......
..llllllllll......
..llllllllll......
....kk...kk.......
....kk...kk.......
....kk...kk.......
...SSS..SSS.......
...SSS..SSS.......
`;

  function sprite(grid, palette) {
    const rows = grid.split('\n').filter(r => r.length);
    let out = '';
    for (let y = 0; y < rows.length; y++) {
      const row = rows[y];
      let x = 0;
      while (x < row.length) {
        const c = row[x];
        if (c === '.' || c === ' ' || !palette[c]) { x++; continue; }
        let run = 1;
        while (x + run < row.length && row[x + run] === c) run++;
        out += `<rect x="${x}" y="${y}" width="${run}" height="1" fill="${palette[c]}"/>`;
        x += run;
      }
    }
    return out;
  }

  const RECTS = sprite(GRID, PAL);

  window.beamMascot = function (opts) {
    opts = opts || {};
    const cls = opts.className || '';
    return `<svg class="beam-mascot-svg ${cls}" viewBox="0 0 18 26" ` +
      `shape-rendering="crispEdges" preserveAspectRatio="xMidYMax meet" ` +
      `xmlns="http://www.w3.org/2000/svg" aria-hidden="true">${RECTS}</svg>`;
  };
})();
